import static de.gematik.demis.bulk.inbound.service.config.RabbitConfig.IN_QUEUE;
import static de.gematik.demis.bulk.inbound.service.config.RabbitConfig.ROUTING_KEY_IN;

import org.springframework.amqp.core.Binding;
import org.springframework.amqp.core.BindingBuilder;
import org.springframework.amqp.core.DirectExchange;
import org.springframework.amqp.core.Queue;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.context.annotation.Profile;

@Configuration
@Profile("test")
public class InQueueConfiguration extends QueuesConfiguration {

  @Bean
  public Queue inQueue() {
    return createDurableQueue(IN_QUEUE);
  }

  @Bean
  public Binding inBinding(final Queue inQueue, final DirectExchange bulkExchange) {
    return BindingBuilder.bind(inQueue).to(bulkExchange).with(ROUTING_KEY_IN);
  }
}
