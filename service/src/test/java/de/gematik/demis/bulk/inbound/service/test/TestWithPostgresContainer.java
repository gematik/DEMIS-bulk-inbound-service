import static de.gematik.demis.bulk.inbound.service.test.TestContainer.POSTGRES_CONTAINER;

import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase;
import org.springframework.boot.jdbc.test.autoconfigure.AutoConfigureTestDatabase.Replace;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

@Testcontainers
@AutoConfigureTestDatabase(replace = Replace.NONE)
@DirtiesContext
@ActiveProfiles("database-test")
public abstract class TestWithPostgresContainer {

  @Container @ServiceConnection protected static PostgreSQLContainer postgres = POSTGRES_CONTAINER;

  @DynamicPropertySource
  protected static void postgresqlProperties(final DynamicPropertyRegistry registry) {
    registry.add("spring.liquibase.url", postgres::getJdbcUrl);
    registry.add("spring.liquibase.parameters.db-user-service", postgres::getUsername);
  }
}
